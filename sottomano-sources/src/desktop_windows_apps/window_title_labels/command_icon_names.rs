const SCRIPT_ICONS: &[(&str, &str)] = &[
    (".nu", "system-run"),
    (".sh", "system-run"),
    (".py", "python"),
];

pub fn command_icon(command: &str) -> Option<String> {
    CMD_ICONS
        .iter()
        .find(|(cmd, _)| *cmd == command)
        .or_else(|| {
            SCRIPT_ICONS
                .iter()
                .find(|(extension, _)| command.ends_with(*extension))
        })
        .map(|(_, icon)| (*icon).to_string())
}
