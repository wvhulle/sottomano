//! Generates the [`Icon`] enum from `iced_font_awesome`'s own bundled icon
//! metadata — the exact `icons-light.json` that crate reads at runtime to
//! resolve a name into a glyph. One variant per solid icon, so referencing an
//! icon that does not exist is a compile error, and the list can never drift
//! from what actually renders: there is no vendored copy and no hand-written
//! table.

use std::{
    collections::HashSet,
    env,
    fmt::Write,
    fs,
    path::{Path, PathBuf},
    process::Command,
};

/// Single-character digit slugs (`0`..=`9`) can't be identifiers; name them.
const DIGIT_WORDS: [&str; 10] = [
    "Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine",
];

fn to_ident(slug: &str) -> String {
    if slug.len() == 1
        && let Some(d) = slug.chars().next().and_then(|c| c.to_digit(10))
    {
        return DIGIT_WORDS[d as usize].to_owned();
    }
    slug.split('-')
        .map(|seg| {
            let mut chars = seg.chars();
            match chars.next() {
                Some(first) => first.to_ascii_uppercase().to_string() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

/// Locate `icons-light.json` inside the resolved `iced_font_awesome` source,
/// via `cargo metadata` — the only cross-environment way (registry, Nix vendor
/// dir) to find a dependency's non-Rust assets.
fn metadata_json_path() -> PathBuf {
    let cargo = env::var_os("CARGO").unwrap_or_else(|| "cargo".into());
    let output = Command::new(cargo)
        .args(["metadata", "--format-version", "1"])
        .output()
        .expect("failed to run `cargo metadata`");
    assert!(output.status.success(), "`cargo metadata` failed");

    let meta: serde_json::Value = serde_json::from_slice(&output.stdout).unwrap();
    let manifest = meta["packages"]
        .as_array()
        .unwrap()
        .iter()
        .find(|p| p["name"] == "iced_font_awesome")
        .expect("iced_font_awesome not among resolved dependencies")["manifest_path"]
        .as_str()
        .unwrap();

    Path::new(manifest)
        .parent()
        .unwrap()
        .join("assets/font-awesome-7/icons-light.json")
}

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=Cargo.lock");

    let json_path = metadata_json_path();
    println!("cargo:rerun-if-changed={}", json_path.display());

    let metadata: serde_json::Value =
        serde_json::from_str(&fs::read_to_string(&json_path).unwrap()).unwrap();

    let mut slugs: Vec<&str> = metadata
        .as_array()
        .unwrap()
        .iter()
        .filter(|icon| {
            icon["styles"]
                .as_array()
                .is_some_and(|s| s.iter().any(|s| s == "solid"))
        })
        .map(|icon| icon["label"].as_str().unwrap())
        .collect();
    slugs.sort_unstable();
    slugs.dedup();

    let mut variants = String::new();
    let mut arms = String::new();
    let mut seen = HashSet::new();

    for slug in slugs {
        let ident = to_ident(slug);
        assert!(
            ident.starts_with(|c: char| c.is_ascii_alphabetic() || c == '_'),
            "slug {slug:?} produced invalid Rust identifier {ident:?}",
        );
        assert!(
            seen.insert(ident.clone()),
            "slug {slug:?} produced duplicate identifier {ident:?}",
        );
        writeln!(variants, "    {ident},").unwrap();
        writeln!(arms, "            Icon::{ident} => {slug:?},").unwrap();
    }

    let code = format!(
        r"// @generated by build.rs from iced_font_awesome's icons-light.json — do not edit.
/// A Font Awesome 7 solid icon. One variant per icon in the font, so a
/// reference to a nonexistent icon fails to compile.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[allow(dead_code)] // the whole font is exposed; most variants go unused
pub enum Icon {{
{variants}}}

impl Icon {{
    /// The Font Awesome slug backing this icon.
    #[allow(clippy::too_many_lines)]
    pub const fn name(self) -> &'static str {{
        match self {{
{arms}        }}
    }}
}}
",
    );

    fs::write(
        Path::new(&env::var("OUT_DIR").unwrap()).join("icons.rs"),
        code,
    )
    .unwrap();
}
